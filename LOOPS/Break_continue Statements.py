#break statement:it is used to stop a loop imediately.

for i in range(1,11):
    if i ==5:
        break
    print(i)

#continue statement:is used to skip the current iteration of a loop and move to the next iteration immediately.
for i in range(0,21):
    if i == 10:
        continue
    print(i)

